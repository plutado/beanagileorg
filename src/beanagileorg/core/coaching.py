def guide(slug: str) -> dict | None:
    return next((g for g in GUIDES if g["slug"] == slug), None)


def phase_for(day: int | None) -> str:
    if day is None:
        return "Any time"
    for name, lo, hi, _ in REFLECTION_PHASES:
        if (lo is None or day >= lo) and (hi is None or day <= hi):
            return name
    return "Any time"


